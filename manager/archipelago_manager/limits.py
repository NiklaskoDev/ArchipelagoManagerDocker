"""What players who are not organizers may have of the games they generate (when the settings let them generate).

- A game they generate has at most MAX_WORLDS worlds: one for each player in the chosen files.
- At most MAX_UNFINISHED of their games are unfinished: not in the archive yet, or still being generated.
- At most MAX_RUNNING of them run at a time. A game asleep until its players come back counts as running: it wakes up
  by itself.

Administrators and organizers have no such limits, neither for their own games nor when they start someone else's.
"""
from __future__ import annotations

import asyncio
import contextlib
import sqlite3
from collections.abc import AsyncIterator

from . import db

MAX_WORLDS = 15
MAX_UNFINISHED = 3
MAX_RUNNING = 1

# Checking the count and queueing the generation is one step, so two requests at once cannot both take the last place;
# likewise checking and starting a server, which is recorded as running only once its process is there
GENERATING = asyncio.Lock()
STARTING = asyncio.Lock()


class LimitError(Exception):
    def __init__(self, message: str) -> None:
        super().__init__(message)
        self.message = message


def applies(user_id: int | None) -> bool:
    """Whether the limits hold for the games of this user: a player, not an organizer or administrator."""
    row = db.query_one("SELECT role FROM users WHERE id = ?", (user_id,)) if user_id is not None else None
    return bool(row) and row["role"] == "user"


def unfinished(user_id: int) -> int:
    """The user's games that are not in the archive, and their generations still under way."""
    games = db.query_one("SELECT COUNT(*) AS n FROM games WHERE created_by = ? AND finished_at IS NULL", (user_id,))["n"]
    jobs = db.query_one("SELECT COUNT(*) AS n FROM jobs WHERE created_by = ? AND status IN ('queued', 'running')",
                        (user_id,))["n"]
    return games + jobs


def _on(game: sqlite3.Row) -> bool:
    """Running, starting, or asleep until a player comes back (rooms.RoomManager.is_asleep)."""
    return game["desired_state"] == "running" or bool(game["asleep"])


def running(user_id: int, *, besides: int | None = None) -> list[sqlite3.Row]:
    """The user's games that run (or sleep), other than `besides`."""
    return [g for g in db.query("SELECT id, name, desired_state, asleep FROM games WHERE created_by = ? AND id != ?",
                                (user_id, besides or 0)) if _on(g)]


def check_generation(user: sqlite3.Row, worlds: int) -> None:
    """Before a player's generation is queued."""
    if user["role"] != "user":
        return
    if worlds > MAX_WORLDS:
        raise LimitError(f"A game you generate can have at most {MAX_WORLDS} worlds, and these configs hold {worlds}")
    if unfinished(user["id"]) >= MAX_UNFINISHED:
        raise LimitError(f"You already have {MAX_UNFINISHED} unfinished games of your own (counting those being "
                         f"generated). Move one to the archive before you generate another.")


def check_start(game: sqlite3.Row, actor: sqlite3.Row | None) -> None:
    """Before a game generated by a player starts. `actor` is who starts it; None for the manager itself, after
    generating. A game that already runs (or sleeps) can always restart."""
    if actor is not None and actor["role"] != "user":
        return
    if _on(game) or not applies(game["created_by"]):
        return
    others = running(game["created_by"], besides=game["id"])
    if len(others) < MAX_RUNNING:
        return
    if actor is None or actor["id"] == game["created_by"]:
        raise LimitError(f"You can have one of your games running at a time, and {others[0]['name']} is running (or "
                         f"asleep until its players come back). Stop it first.")
    creator = db.query_one("SELECT username FROM users WHERE id = ?", (game["created_by"],))["username"]
    raise LimitError(f"Only one game of {creator} can run at a time, and {others[0]['name']} is running (or asleep "
                     f"until its players come back). It has to be stopped first.")


@contextlib.asynccontextmanager
async def starting(game: sqlite3.Row, actor: sqlite3.Row | None) -> AsyncIterator[None]:
    """Around starting a game's server: check_start, and the place stays taken until the start is done."""
    async with STARTING:
        check_start(game, actor)
        yield


def check_unarchive(game: sqlite3.Row, actor: sqlite3.Row) -> None:
    """Before a game generated by a player comes back out of the archive."""
    if actor["role"] != "user" or not applies(game["created_by"]):
        return
    if unfinished(game["created_by"]) >= MAX_UNFINISHED:
        raise LimitError(f"There are {MAX_UNFINISHED} unfinished games of this player already. Move one of them to the "
                         f"archive first.")


def summary(user: sqlite3.Row) -> dict | None:
    """The limits as the web UI shows them to a player; None for organizers and administrators."""
    if user["role"] != "user":
        return None
    return {"worlds": MAX_WORLDS, "unfinished": MAX_UNFINISHED, "running": MAX_RUNNING,
            "unfinished_now": unfinished(user["id"])}
